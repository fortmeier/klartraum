/**
 * TESTS:
 * - firstBlockMatchesDiffusers: the image and text streams after the input layers and the first block match diffusers'
 *   QwenImageTransformerBlock on the same dequantized weights
 * - velocityMatchesDiffusers: the velocity prediction of all 60 blocks and the output layers matches the reference
 * - loraVelocityMatchesMergedReference: with the Lightning LoRA added at run time, the velocity matches the reference
 *   whose weights have the LoRA merged in, and is far from the velocity without it
 *
 * The references are generated by scripts/qwen_image/dit_reference.py (with and without --lora) into
 * build/models/qwen-image/reference/ from the GGUFs in build/models/qwen-image/ (neither is in the repository); the
 * tests skip without them.
 **/

#include <gtest/gtest.h>

#include <algorithm>
#include <cmath>
#include <filesystem>
#include <fstream>

#include "klartraum/computegraph/computegraph.hpp"
#include "klartraum/diffusion/qwen_image_transformer.hpp"
#include "klartraum/headless_frontend.hpp"

using namespace klartraum;

namespace {

const std::string kModel = "./build/models/qwen-image/transformer/qwen-image-Q4_K_S.gguf";
const std::string kLora = "./build/models/qwen-image/lightning/Qwen-Image-Lightning-8steps-V2.0.gguf";
const std::string kReference = "./build/models/qwen-image/reference/";

std::vector<float> readFloats(const std::string& path) {
    std::ifstream file(path, std::ios::binary | std::ios::ate);
    std::vector<float> data(static_cast<size_t>(file.tellg()) / sizeof(float));
    file.seekg(0);
    file.read(reinterpret_cast<char*>(data.data()), static_cast<std::streamsize>(data.size() * sizeof(float)));
    return data;
}

bool referencesExist(const std::string& output) {
    return std::filesystem::exists(kModel) && std::filesystem::exists(kReference + "dit_config.txt") &&
           std::filesystem::exists(kReference + output);
}

struct Result {
    std::vector<float> image, text, velocity;
};

// Runs the transformer (all blocks, or only the first @p blocks) on the reference inputs.
Result run(uint32_t blocks, const std::string& lora = "") {
    uint32_t height = 0, width = 0, textTokens = 0;
    float sigma = 0.0f;
    std::ifstream(kReference + "dit_config.txt") >> height >> width >> textTokens >> sigma;
    HeadlessFrontend frontend;
    auto& vc = frontend.getKlartraumEngine().getVulkanContext();
    auto transformer =
        vc.create<QwenImageTransformer>(kModel, QwenImageTransformerOptions{height, width, textTokens, lora, blocks});
    ComputeGraph graph(vc, 1);
    graph.compileFrom(transformer);
    transformer->setPromptEmbedding(readFloats(kReference + "dit_text_f32.bin"));
    transformer->setLatent(readFloats(kReference + "dit_latent_f32.bin"));
    transformer->setSigma(sigma);
    graph.submitAndWait(vc.getGraphicsQueue(), 0);
    return {transformer->readImageStates(), transformer->readTextStates(),
            blocks == 0 ? transformer->readVelocity() : std::vector<float>{}};
}

// Per token, the largest difference relative to the token's largest reference magnitude; returns the worst token's.
float worstRelativeError(const std::vector<float>& actual, const std::vector<float>& expected, uint32_t width) {
    EXPECT_EQ(actual.size(), expected.size());
    float worst = 0.0f;
    for (size_t token = 0; token < std::min(actual.size(), expected.size()) / width; ++token) {
        float difference = 0.0f, magnitude = 0.0f;
        for (size_t i = token * width; i < (token + 1) * width; ++i) {
            difference = std::max(difference, std::abs(actual[i] - expected[i]));
            magnitude = std::max(magnitude, std::abs(expected[i]));
        }
        worst = std::max(worst, difference / magnitude);
    }
    return worst;
}

} // namespace

TEST(QwenImageTransformerTest, firstBlockMatchesDiffusers) {
    if (!referencesExist("dit_block0_image_f32.bin"))
        GTEST_SKIP() << "run scripts/qwen_image/dit_reference.py first";
    const auto result = run(1);
    const float image = worstRelativeError(result.image, readFloats(kReference + "dit_block0_image_f32.bin"), 3072);
    const float text = worstRelativeError(result.text, readFloats(kReference + "dit_block0_text_f32.bin"), 3072);
    std::cout << "relative error: image " << image << ", text " << text << std::endl;
    EXPECT_LT(image, 1e-3f);
    EXPECT_LT(text, 1e-3f);
}

TEST(QwenImageTransformerTest, velocityMatchesDiffusers) {
    if (!referencesExist("dit_output_f32.bin"))
        GTEST_SKIP() << "run scripts/qwen_image/dit_reference.py first";
    const float error = worstRelativeError(run(0).velocity, readFloats(kReference + "dit_output_f32.bin"), 64);
    std::cout << "relative error: " << error << std::endl;
    EXPECT_LT(error, 1e-2f);
}

TEST(QwenImageTransformerTest, loraVelocityMatchesMergedReference) {
    if (!referencesExist("dit_output_lora_f32.bin") || !referencesExist("dit_output_f32.bin") ||
        !std::filesystem::exists(kLora))
        GTEST_SKIP() << "run scripts/qwen_image/dit_reference.py --lora first";
    const auto velocity = run(0, kLora).velocity;
    const float error = worstRelativeError(velocity, readFloats(kReference + "dit_output_lora_f32.bin"), 64);
    const float withoutLora = worstRelativeError(velocity, readFloats(kReference + "dit_output_f32.bin"), 64);
    std::cout << "relative error: " << error << ", to the velocity without the LoRA: " << withoutLora << std::endl;
    // The LoRA moves the velocity by 20 % to 50 % per token; adding its low-rank products instead of merging them
    // into the weights rounds differently, which the 60 blocks amplify to about 1 %.
    EXPECT_LT(error, 2e-2f);
    EXPECT_GT(withoutLora, 0.1f);
}
